def _rng(seed: int):
    state = [seed]

    def r() -> float:
        state[0] = (state[0] * 1103515245 + 12345) % (2 ** 31)
        return state[0] / 2 ** 31
    return r


def _cliff(side: str, c: dict, r) -> str:
    pts = []
    y = -20
    while y < 1960:
        x = 70 + r() * 55
        pts.append((x, y))
        y += 90 + r() * 80
    pts.append((80, 1960))
    if side == "right":
        pts = [(1080 - x, y) for x, y in pts]
        edge = " ".join(f"{x:.0f},{y:.0f}" for x, y in pts)
        poly = f"1100,-20 {edge} 1100,1960"
    else:
        edge = " ".join(f"{x:.0f},{y:.0f}" for x, y in pts)
        poly = f"-20,-20 {edge} -20,1960"
    rim = " ".join(f"{x:.0f},{y:.0f}" for x, y in pts)
    out = f'<polygon points="{poly}" fill="{c["cliff"]}" stroke="{OUTLINE}" stroke-width="6" stroke-linejoin="round"/>'
    out += f'<polyline points="{rim}" fill="none" stroke="{c["cliff_light"]}" stroke-width="10" stroke-linejoin="round" opacity="0.7" transform="translate({-8 if side == "left" else 8},0)"/>'
    for _ in range(9):
        x = (30 + r() * 70) if side == "left" else (1080 - 30 - r() * 70)
        yy = r() * 1900
        out += f'<path d="M{x:.0f} {yy:.0f} l{r()*30-15:.0f} {40+r()*40:.0f}" stroke="{c["cliff_dark"]}" stroke-width="6" stroke-linecap="round" opacity="0.6"/>'
    return out


def _rocks(c: dict, r, n: int) -> str:
    out = ""
    for _ in range(n):
        x, y = 200 + r() * 680, 120 + r() * 1700
        w, h = 18 + r() * 30, 10 + r() * 16
        out += f'<ellipse cx="{x:.0f}" cy="{y:.0f}" rx="{w:.0f}" ry="{h:.0f}" fill="{c["rock"]}" stroke="{OUTLINE}" stroke-width="4" opacity="0.85"/>'
        out += f'<ellipse cx="{x - w * 0.25:.0f}" cy="{y - h * 0.3:.0f}" rx="{w * 0.4:.0f}" ry="{h * 0.3:.0f}" fill="#ffffff" opacity="0.25"/>'
    for _ in range(26):
        x, y = 200 + r() * 680, r() * 1920
        out += f'<path d="M{x:.0f} {y:.0f} l{r()*40-20:.0f} {r()*30+10:.0f} l{r()*30-15:.0f} {r()*30+10:.0f}" fill="none" stroke="{c["detail"]}" stroke-width="4" stroke-linecap="round" opacity="0.45"/>'
    return out


def _motif(c: dict, r) -> str:
    m = c["motif"]
    if m == "dunes":
        return "".join(
            f'<path d="M200 {y} C400 {y - 40} 680 {y + 40} 880 {y}" fill="none" stroke="{c["cliff_light"]}" stroke-width="8" opacity="0.35"/>'
            for y in range(240, 1900, 260))
    if m == "rune":
        return (f'<g opacity="0.35" fill="none" stroke="{c["cliff_dark"]}" stroke-width="10">'
                '<path d="M540 200 L700 520 L540 840 L380 520 Z"/><path d="M540 330 L630 520 L540 710 L450 520 Z"/>'
                '<path d="M540 840 L540 1500"/><path d="M380 1000 L540 1160 L700 1000"/></g>')
    if m == "tiles":
        out = '<g stroke="#1b1622" stroke-width="5" opacity="0.6">'
        for y in range(0, 1920, 120):
            out += f'<line x1="180" y1="{y}" x2="900" y2="{y}"/>'
            off = 0 if (y // 120) % 2 else 60
            for x in range(180 + off, 900, 120):
                out += f'<line x1="{x}" y1="{y}" x2="{x}" y2="{y + 120}"/>'
        return out + "</g>"
    out = ""
    for _ in range(40):
        x, y, rad = 180 + r() * 720, r() * 1920, 4 + r() * 14
        out += f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{rad:.0f}" fill="none" stroke="#bff6ff" stroke-width="3" opacity="0.35"/>'
    return out


def make_backgrounds() -> None:
    out = HD / "bg"
    out.mkdir(parents=True, exist_ok=True)
    for i, (name, c) in enumerate(THEMES.items()):
        r = _rng(1234 + i * 77)
        svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1920" viewBox="0 0 1080 1920">
  <!-- Stage background ({name}). Generated by tools/hd_art.py -->
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{c["top"]}"/><stop offset="1" stop-color="{c["low"]}"/>
    </linearGradient>
  </defs>
  <rect width="1080" height="1920" fill="url(#g)"/>
  <rect x="250" y="-20" width="580" height="1960" rx="60" fill="{c["path"]}" opacity="0.7"/>
  <rect x="250" y="-20" width="580" height="1960" rx="60" fill="none" stroke="{c["path_edge"]}" stroke-width="10" opacity="0.6"/>
  {_motif(c, r)}
  {_rocks(c, r, 10)}
  {_cliff("left", c, r)}
  {_cliff("right", c, r)}
</svg>
"""
        (out / f"{name}.svg").write_text(svg)


